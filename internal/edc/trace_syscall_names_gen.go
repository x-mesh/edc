//go:build ignore

// trace_syscall_names.go를 만든다. syscall 번호는 아키텍처마다 다르고, golang.org/x/sys가 kernel header에서 만든
// 번호 표를 이미 담고 있다. 그 파일을 읽어 trace syscall이 쓰는 이름 표로 바꾼다.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var line = regexp.MustCompile(`^\s+SYS_([A-Z0-9_]+)\s+= ([0-9]+)$`)

func main() {
	output, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		fail(err)
	}
	dir := filepath.Join(strings.TrimSpace(string(output)), "unix")
	var source bytes.Buffer
	source.WriteString("// Code generated by trace_syscall_names_gen.go from golang.org/x/sys/unix. DO NOT EDIT.\n\npackage edc\n\n")
	source.WriteString("// syscallNameTables는 GOARCH별 syscall 이름이다. index가 번호다. 386 표는 amd64의 32비트 호환 호출에 쓴다.\n")
	source.WriteString("var syscallNameTables = map[string][]string{\n")
	for _, arch := range []string{"386", "amd64", "arm64"} {
		names, err := read(filepath.Join(dir, "zsysnum_linux_"+arch+".go"))
		if err != nil {
			fail(err)
		}
		fmt.Fprintf(&source, "%q: {", arch)
		for index, name := range names {
			if index%8 == 0 {
				source.WriteString("\n")
			}
			fmt.Fprintf(&source, "%q, ", name)
		}
		source.WriteString("\n},\n")
	}
	source.WriteString("}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("trace_syscall_names.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

func read(path string) ([]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	numbered := map[int]string{}
	last := -1
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		match := line.FindStringSubmatch(scanner.Text())
		if match == nil {
			continue
		}
		number, err := strconv.Atoi(match[2])
		if err != nil {
			return nil, err
		}
		numbered[number] = strings.ToLower(match[1])
		last = max(last, number)
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if last < 0 {
		return nil, fmt.Errorf("%s has no syscall numbers", path)
	}
	names := make([]string, last+1)
	for number, name := range numbered {
		names[number] = name
	}
	return names, nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "trace_syscall_names_gen:", err)
	os.Exit(1)
}
